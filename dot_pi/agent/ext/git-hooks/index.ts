/**
 * Git hooks 自动配置扩展（git-hooks）
 *
 * session_start 时对 cwd 所属 git 仓库检测 hooks 配置状态，缺失时自动补配并提示：
 *
 * 1. githooks 分支：仓库根 .githooks/ 目录存在且含可执行脚本时，视为项目自定义
 *    hooks 约定（githooks 优先）——core.hooksPath 未设则设为 .githooks；已设为
 *    .githooks 视为已就绪；已指向其他值视为用户明确配置，不动仅提示现状。
 * 2. pre-commit 分支：仓库根有 .pre-commit-config.yaml 且系统装有 pre-commit
 *    命令时，hook 未安装则运行 pre-commit install；工具缺失属前置条件不满足，
 *    静默跳过。
 *
 * 互斥锚定（2026-10-17 实测 pre-commit 4.6.2）：core.hooksPath 已设时
 * pre-commit install 直接拒绝执行（Cowardly refusing to install hooks with
 * core.hooksPath set），两功能天然互斥，githooks 命中即完成分流，不再探测
 * pre-commit；同存 .pre-commit-config.yaml 时提示已被 hooksPath 接管。
 *
 * 已装判定：hooks 目录下 pre-commit 文件头部含 "# File generated by pre-commit"
 * 标记（install 产物锚点）；存在外来旧 hook 时直接交工具处理（4.x 自带
 * migration mode，旧 hook 改名 .legacy 保留，实测退出码 0）。hooks 目录用
 * git rev-parse --git-path hooks 解析，兼容 worktree 的 gitfile 布局。
 *
 * 提示通道（models-dev 同款决策）：激活与知情提示走 setWidget 独立槽，弃用
 * notify——notify info 与 pi 默认提示共用 chat 状态行单槽，背靠背原位覆写互挤；
 * 激活提示 8 秒自动清除，失败提示不自动清（错误值得停留）；已就绪（无需任何
 * 修改）零输出。非 tui 模式（print/json/rpc 无 widget 组件通道）打一行摘要到
 * stderr，不污染 stdout 的机读输出。
 *
 * 幂等：所有 session_start reason 都重检测（/new、/reload 重绑会话时 widget 区
 * 被清空，需补挂）；重挂前清掉上一个延时器；自动清除用的上下文在 reload 后会
 * stale，try/catch 吞掉即可（models-dev 先例）。
 *
 * 边界：仅 session_start 检测一次，会话中途 cd 到其他仓库不检测；Windows 无
 * 执行位语义，可执行判定退化为"目录含文件"（NTFS stat 恒带执行位），可接受
 * 不特判；core.hooksPath 就绪判定仅精确匹配 ".githooks"（本扩展写出的形态），
 * 绝对路径等价形态归入"已指向别处"如实提示。
 */

import { execFile } from "node:child_process";
import { readdir, readFile, stat } from "node:fs/promises";
import { basename, isAbsolute, join, resolve } from "node:path";
import { promisify } from "node:util";

import type { ExtensionAPI, ExtensionContext } from "@earendil-works/pi-coding-agent";
import { Text } from "@earendil-works/pi-tui";

const execFileAsync = promisify(execFile);

const WIDGET_KEY = "git-hooks";
/** 激活提示自动清除延时（models-dev 启动提示同款） */
const VISIBLE_MS = 8000;
/** 识别 pre-commit 生成 hook 的头部标记 */
const PRE_COMMIT_MARKER = "# File generated by pre-commit";

let dismissTimer: ReturnType<typeof setTimeout> | undefined;

interface Notice {
  lines: string[];
  /** 失败提示不自动清除 */
  failed: boolean;
}

export default function (pi: ExtensionAPI): void {
  pi.on("session_start", async (_event, ctx) => {
    try {
      const notice = await checkRepository(ctx.cwd);
      if (notice) {
        mount(ctx, notice);
      }
    } catch (error) {
      console.error(`[git-hooks] ${message(error)}`);
    }
  });
}

/** 检测流程主干：小分支提前返回，只对需要动手或需要知情的仓库产出提示 */
async function checkRepository(cwd: string): Promise<Notice | undefined> {
  const toplevel = await topLevel(cwd);
  if (!toplevel) {
    return undefined;
  }
  const [hasPreCommitConfig, githooksTaken] = await Promise.all([
    exists(join(toplevel, ".pre-commit-config.yaml")),
    hasExecutableScript(join(toplevel, ".githooks")),
  ]);
  if (githooksTaken) {
    return configureHooksPath(toplevel, hasPreCommitConfig);
  }
  if (hasPreCommitConfig) {
    return installPreCommit(toplevel);
  }
  return undefined;
}

/** 处理 githooks 分支：core.hooksPath 三态分流（未设补配 / 已就绪静默 / 指向别处提示） */
async function configureHooksPath(
  toplevel: string,
  hasPreCommitConfig: boolean,
): Promise<Notice | undefined> {
  const current = await gitConfig(toplevel, "core.hooksPath");
  if (current === ".githooks") {
    return undefined;
  }
  const lines: string[] = [];
  let failed = false;
  if (current === undefined) {
    try {
      await execFileAsync("git", ["config", "core.hooksPath", ".githooks"], { cwd: toplevel });
      lines.push(
        `git-hooks（${basename(toplevel)}）：已设置 core.hooksPath=.githooks（.githooks/ 含可执行脚本）`,
      );
    } catch (error) {
      lines.push(`git-hooks：core.hooksPath 写入失败：${message(error)}`);
      failed = true;
    }
  } else {
    lines.push(`git-hooks（${basename(toplevel)}）：core.hooksPath=${current}（已有配置，未改动）`);
  }
  if (hasPreCommitConfig) {
    lines.push("检测到 .pre-commit-config.yaml：hooks 已由 core.hooksPath 接管，跳过 pre-commit");
  }
  return { lines, failed };
}

/** 处理 pre-commit 分支：工具存在性 → 已装判定 → 安装，前置不满足一律静默 */
async function installPreCommit(toplevel: string): Promise<Notice | undefined> {
  try {
    await execFileAsync("pre-commit", ["--version"]);
  } catch {
    return undefined;
  }
  if (await preCommitInstalled(toplevel)) {
    return undefined;
  }
  try {
    await execFileAsync("pre-commit", ["install"], { cwd: toplevel });
    return {
      lines: [`git-hooks（${basename(toplevel)}）：已运行 pre-commit install`],
      failed: false,
    };
  } catch (error) {
    return { lines: [`git-hooks：pre-commit install 失败：${message(error)}`], failed: true };
  }
}

/** 仓库根解析：cwd 不在 git 仓库内返回 undefined */
async function topLevel(cwd: string): Promise<string | undefined> {
  try {
    const { stdout } = await execFileAsync("git", ["rev-parse", "--show-toplevel"], { cwd });
    return stdout.trim() || undefined;
  } catch {
    return undefined;
  }
}

/** 读仓库生效的 git 配置：键未设置返回 undefined，git 本身异常向上抛 */
async function gitConfig(cwd: string, key: string): Promise<string | undefined> {
  try {
    const { stdout } = await execFileAsync("git", ["config", key], { cwd });
    return stdout.trim();
  } catch (error) {
    if ((error as { code?: number | string }).code === 1) {
      return undefined;
    }
    throw error;
  }
}

/** 检查 hooks 目录下是否已存在 pre-commit 生成的 hook（按头部标记判定） */
async function preCommitInstalled(toplevel: string): Promise<boolean> {
  let hooksDir: string;
  try {
    const { stdout } = await execFileAsync("git", ["rev-parse", "--git-path", "hooks"], {
      cwd: toplevel,
    });
    const dir = stdout.trim();
    if (!dir) {
      return false;
    }
    hooksDir = isAbsolute(dir) ? dir : resolve(toplevel, dir);
  } catch {
    return false;
  }
  try {
    const hook = await readFile(join(hooksDir, "pre-commit"), "utf8");
    return hook.includes(PRE_COMMIT_MARKER);
  } catch {
    return false;
  }
}

/** .githooks/ 是否含至少一个可执行脚本文件（Windows 上 stat 恒带执行位，退化为目录含文件） */
async function hasExecutableScript(dir: string): Promise<boolean> {
  const entries = await readdir(dir, { withFileTypes: true }).catch(() => undefined);
  if (!entries) {
    return false;
  }
  const stats = await Promise.all(
    entries
      .filter((entry) => entry.isFile())
      .map((entry) => stat(join(dir, entry.name)).catch(() => undefined)),
  );
  return stats.some((st) => st !== undefined && (st.mode & 0o111) !== 0);
}

async function exists(path: string): Promise<boolean> {
  try {
    await stat(path);
    return true;
  } catch {
    return false;
  }
}

/** 提示挂载：tui 走 widget（激活态定时清除），其余模式打 stderr 摘要 */
function mount(ctx: ExtensionContext, notice: Notice): void {
  if (ctx.mode === "tui") {
    ctx.ui.setWidget(
      WIDGET_KEY,
      (_tui, theme) => new Text(notice.lines.map((line) => theme.fg("dim", line)).join("\n"), 1, 0),
    );
    clearTimeout(dismissTimer);
    if (!notice.failed) {
      dismissTimer = setTimeout(() => {
        try {
          ctx.ui.setWidget(WIDGET_KEY, undefined);
        } catch {
          // 上下文已随 /reload 失效：widget 已被重绑流程清空，无需处理
        }
      }, VISIBLE_MS);
    }
  } else {
    console.error(notice.lines.join("；"));
  }
}

function message(error: unknown): string {
  if (error instanceof Error) {
    const execErr = error as NodeJS.ErrnoException & { stdout?: string; stderr?: string };
    // 工具的用户可见错误流向：pre-commit 走 stdout（如 Cowardly refusing），git 走 stderr，两条都试
    const detail = [execErr.stderr, execErr.stdout]
      .flatMap((text) => text?.trim().split("\n")[0] ?? [])
      .find((line) => line.length > 0);
    return detail ?? execErr.message;
  }
  return String(error);
}
